/**
 * True for paths whose extension marks them as binary. Used only when a source does not say
 * whether a file is binary (the GitHub files API has no such flag).
 */
export function isLikelyBinaryPath(path: string): boolean {
  const base = basename(path).toLowerCase();
  const dot = base.lastIndexOf('.');
  if (dot <= 0) return false;
  return BINARY_EXTENSIONS.has(base.slice(dot + 1));
}
